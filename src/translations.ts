// Safe Proxy translation getter that looks up the exact language dictionary
export const translations = new Proxy(allDictionaries, {
  get(target, lang: string) {
    const chosenLang = (lang in target ? lang : 'hi') as Language;
    const langDict = target[chosenLang] || target.hi;
    return new Proxy(langDict, {
      get(dictTarget, key: string) {
        return dictTarget[key] || target.hi[key] || target.en[key] || key;
      }
    });
  }
});
